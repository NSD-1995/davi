require('reflect-metadata');
const test=require('node:test'),assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {PrismaClient}=require('@prisma/client');
const {StaffAttendanceService}=require('../dist/attendance/staff-attendance.service');
const {OperationsAccessService}=require('../dist/auth/operations-access.service');
const {AttendanceService}=require('../dist/attendance/attendance.service');
const {SchoolOperationsService}=require('../dist/attendance/school-operations.service');
test('PostgreSQL: roster, bulk audit, corrections, locks, isolation and holidays',{skip:process.env.OPERATIONS_DB_TEST!=='1'},async()=>{
 const p=new PrismaClient();
 try{await p.$transaction(async tx=>{
  const client=new Proxy(tx,{get(t,k){return k==='$transaction'?fn=>fn(client):Reflect.get(t,k);}});
  const school=await tx.school.create({data:{name:'Attendance fixture',slug:'ops-'+randomUUID()}});
  const admin=await tx.user.create({data:{schoolId:school.id,email:'admin@fixture.invalid',passwordHash:'fixture',firstName:'Admin',lastName:'Fixture'}});
  const role=await tx.role.create({data:{schoolId:school.id,code:'SCHOOL_ADMIN',name:'Admin'}});
  await tx.userRole.create({data:{schoolId:school.id,userId:admin.id,roleId:role.id}});
  const staff=[];
  for(let i=0;i<2;i++){
   const user=await tx.user.create({data:{schoolId:school.id,email:i+'@fixture.invalid',passwordHash:'fixture',firstName:'Staff',lastName:String(i)}});
   staff.push(await tx.staff.create({data:{schoolId:school.id,userId:user.id,employeeId:String(i)}}));
  }
  const coverage={policy:async()=>({timeZone:'Asia/Kolkata'}),reconcile:async()=>({assigned:0})};
  const service=new StaffAttendanceService(client,new OperationsAccessService(client),coverage),date='2026-10-16';
  let roster=await service.roster(school.id,admin.id,date);
  assert.equal(roster.rows.length,2);assert.ok(roster.rows.every(r=>r.attendance.status==='NOT_MARKED'));
  assert.equal(await tx.staffAttendance.count({where:{schoolId:school.id}}),0);
  const saved=await service.bulk(school.id,admin.id,{date,records:staff.map(s=>({staffId:s.id,status:'PRESENT',version:0}))});
  assert.equal(saved.records.length,2);assert.equal(await tx.staffAttendanceAudit.count({where:{schoolId:school.id}}),2);
  await assert.rejects(service.bulk(school.id,admin.id,{date,records:[{staffId:staff[0].id,status:'ABSENT'}]}),/reason/);
  await service.bulk(school.id,admin.id,{date,reason:'Confirmed sick call',records:[{staffId:staff[0].id,status:'ABSENT',version:1}]});
  assert.equal(await tx.staffAttendance.count({where:{schoolId:school.id}}),2);
  await service.lock(school.id,admin.id,{date,locked:true,reason:'Day reviewed'});
  await assert.rejects(service.bulk(school.id,admin.id,{date,reason:'Correction',records:[{staffId:staff[0].id,status:'PRESENT'}]}),/locked/);
  await service.lock(school.id,admin.id,{date,locked:false,reason:'Authorized correction'});
  await assert.rejects(service.roster('foreign-school',admin.id,date),/membership/);
  await assert.rejects(service.roster(school.id,staff[0].userId,date),/permission/);
  await tx.schoolEvent.create({data:{schoolId:school.id,title:'Holiday',eventType:'HOLIDAY',startsAt:new Date('2026-10-19T00:00:00Z')}});
  assert.equal((await service.roster(school.id,admin.id,'2026-10-19')).calendarStatus,'HOLIDAY');
  assert.equal((await service.roster(school.id,admin.id,'2026-10-18')).calendarStatus,'WEEKLY_OFF');
  await tx.schoolEvent.create({data:{schoolId:school.id,title:'Timezone boundary holiday',eventType:'HOLIDAY',startsAt:new Date('2026-10-20T20:00:00Z')}});
  assert.equal((await service.roster(school.id,admin.id,'2026-10-20')).calendarStatus,'WORKING');
  assert.equal((await service.roster(school.id,admin.id,'2026-10-21')).calendarStatus,'HOLIDAY');
  const permission=await tx.permission.findUnique({where:{code:'staff.attendance.view'}});
  const managerRole=await tx.role.create({data:{schoolId:school.id,name:'Scoped manager',code:'FIXTURE_MANAGER',rolePermissions:{create:{permissionId:permission.id}}}});
  await tx.userRole.create({data:{schoolId:school.id,userId:staff[0].userId,roleId:managerRole.id}});
  assert.equal((await service.roster(school.id,staff[0].userId,date)).rows.length,0,'a permission alone grants no delegated staff scope');
  const option=await tx.schoolProfileOption.create({data:{schoolId:school.id,key:'fixture-department',label:'Department'}});
  await tx.userSchoolProfileOption.create({data:{schoolId:school.id,userId:staff[1].userId,optionId:option.id,value:'Office'}});
  await tx.schoolSetting.create({data:{schoolId:school.id,operationsPolicy:{departmentOptionId:option.id,selfAttendanceEnabled:true}}});
  await tx.staffScopeAssignment.create({data:{schoolId:school.id,userId:staff[0].userId,departmentValues:['Office']}});
  const scoped=await service.roster(school.id,staff[0].userId,date);
  assert.equal(scoped.rows.length,1);assert.equal(scoped.rows[0].staffId,staff[1].id);assert.equal(scoped.rows[0].department,'Office');
  await assert.rejects(service.bulk(school.id,staff[0].userId,{date,records:[{staffId:staff[0].id,status:'PRESENT'}]}),/permission/);
  const own=new AttendanceService(client,coverage,service);
  const checkIn=await own.selfCheckIn(school.id,staff[1].userId,new Date('2026-10-16T03:30:00Z'));
  assert.equal(checkIn.status,'PRESENT');
  const again=await own.selfCheckIn(school.id,staff[1].userId,new Date('2026-10-16T04:00:00Z'));
  assert.equal(+again.checkIn,+checkIn.checkIn,'self check-in is idempotent for non-teaching staff');
  const checkedOut=await own.selfCheckOut(school.id,staff[1].userId,new Date('2026-10-16T11:00:00Z'));
  assert.ok(checkedOut.checkOut);assert.equal(checkedOut.source,'SELF_CHECKOUT');
  const operations=new SchoolOperationsService(client,new OperationsAccessService(client),service,coverage);
  const report=await operations.report(school.id,admin.id,date,date);
  assert.equal(report.rows.find(r=>r.staffId===staff[0].id).counts.ABSENT,1);
  const scopedReport=await operations.report(school.id,staff[0].userId,date,date);
  assert.equal(scopedReport.rows.length,1);assert.equal(scopedReport.rows[0].staffId,staff[1].id);
  await assert.rejects(operations.report(school.id,admin.id,'2026-01-01',date),/31 days/);
  throw new Error('ROLLBACK_OPERATIONS');
 },{timeout:30000}).catch(e=>{if(e.message!=='ROLLBACK_OPERATIONS')throw e;});}finally{await p.$disconnect();}
});
